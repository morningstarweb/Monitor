#!/usr/bin/env python3
"""
scripts/sync_brand.py

Reads config/brand.toml and generates type-safe BrandConfig constants
for both Rust (desktop/crates/monitor-core/src/brand_config.rs)
and Kotlin (android/core/common/src/main/kotlin/app/monitor/core/common/BrandConfig.kt).
"""

import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:
    import tomli as tomllib  # type: ignore


def main() -> int:
    workspace_root = Path(__file__).resolve().parent.parent
    brand_toml_path = workspace_root / "config" / "brand.toml"

    if not brand_toml_path.exists():
        print(f"ERROR: {brand_toml_path} not found!", file=sys.stderr)
        return 1

    with open(brand_toml_path, "rb") as f:
        data = tomllib.load(f)

    brand = data["brand"]
    net = data["network"]
    colors = data["colors"]["dark"]

    check_only = "--check" in sys.argv

    # 1. Generate Rust brand_config.rs
    rust_target = workspace_root / "desktop" / "crates" / "monitor-core" / "src" / "brand_config.rs"
    rust_content = f"""// AUTO-GENERATED by scripts/sync_brand.py - DO NOT EDIT MANUALLY
// Source: config/brand.toml

pub const APP_NAME: &str = "{brand['name']}";
pub const APP_SLUG: &str = "{brand['slug']}";
pub const APP_TAGLINE: &str = "{brand['tagline']}";
pub const APP_VERSION: &str = "{brand['version']}";
pub const DEFAULT_PORT: u16 = {net['default_port']};
pub const TAILSCALE_CGNAT_CIDR: &str = "{net['tailscale_cgnat_cidr']}";
pub const LOOPBACK_HOST: &str = "{net['loopback_host']}";

pub mod colors {{
    pub const PRIMARY: &str = "{colors['primary']}";
    pub const PRIMARY_SECONDARY: &str = "{colors['primary_secondary']}";
    pub const ACCENT: &str = "{colors['accent']}";
    pub const SUCCESS: &str = "{colors['success']}";
    pub const WARNING: &str = "{colors['warning']}";
    pub const ERROR: &str = "{colors['error']}";
    pub const SURFACE: &str = "{colors['surface']}";
    pub const CARD: &str = "{colors['card']}";
    pub const BORDER: &str = "{colors['border']}";
    pub const TEXT: &str = "{colors['text']}";
    pub const MUTED_TEXT: &str = "{colors['muted_text']}";
}}
"""

    # 2. Generate Kotlin BrandConfig.kt
    kotlin_target = (
        workspace_root
        / "android"
        / "core"
        / "common"
        / "src"
        / "main"
        / "kotlin"
        / "app"
        / "monitor"
        / "core"
        / "common"
        / "BrandConfig.kt"
    )
    kotlin_content = f"""package app.monitor.core.common

// AUTO-GENERATED by scripts/sync_brand.py - DO NOT EDIT MANUALLY
// Source: config/brand.toml

public object BrandConfig {{
    public const val APP_NAME: String = "{brand['name']}"
    public const val APP_SLUG: String = "{brand['slug']}"
    public const val APP_TAGLINE: String = "{brand['tagline']}"
    public const val APP_VERSION: String = "{brand['version']}"
    public const val DEFAULT_PORT: Int = {net['default_port']}
    public const val TAILSCALE_CGNAT_CIDR: String = "{net['tailscale_cgnat_cidr']}"
    public const val LOOPBACK_HOST: String = "{net['loopback_host']}"

    public object Colors {{
        public const val PRIMARY: String = "{colors['primary']}"
        public const val PRIMARY_SECONDARY: String = "{colors['primary_secondary']}"
        public const val ACCENT: String = "{colors['accent']}"
        public const val SUCCESS: String = "{colors['success']}"
        public const val WARNING: String = "{colors['warning']}"
        public const val ERROR: String = "{colors['error']}"
        public const val SURFACE: String = "{colors['surface']}"
        public const val CARD: String = "{colors['card']}"
        public const val BORDER: String = "{colors['border']}"
        public const val TEXT: String = "{colors['text']}"
        public const val MUTED_TEXT: String = "{colors['muted_text']}"
    }}
}}
"""

    if check_only:
        rust_matches = rust_target.exists() and rust_target.read_text(encoding="utf-8") == rust_content
        kotlin_matches = (
            kotlin_target.exists() and kotlin_target.read_text(encoding="utf-8") == kotlin_content
        )
        if not (rust_matches and kotlin_matches):
            print("ERROR: Generated brand configurations are out of date! Run `python scripts/sync_brand.py`.", file=sys.stderr)
            return 1
        print("Brand configurations match config/brand.toml.")
        return 0

    rust_target.parent.mkdir(parents=True, exist_ok=True)
    rust_target.write_text(rust_content, encoding="utf-8")
    print(f"Wrote {rust_target}")

    kotlin_target.parent.mkdir(parents=True, exist_ok=True)
    kotlin_target.write_text(kotlin_content, encoding="utf-8")
    print(f"Wrote {kotlin_target}")

    return 0


if __name__ == "__main__":
    sys.exit(main())

